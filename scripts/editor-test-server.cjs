// Uses the existing database only to copy fixtures into a disposable schema.
// All application writes and sequences are isolated from published content.
const { Pool } = require('../lib/db/node_modules/pg');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
process.loadEnvFile('.env');
const cleanup = process.argv.find(arg=>arg.startsWith('--cleanup='))?.slice('--cleanup='.length);
const schema = cleanup || `editor_test_${Date.now()}`;
if (!/^editor_test_\d+$/.test(schema)) throw new Error('Invalid test schema');
const pool = new Pool({ connectionString: process.env.DATABASE_URL });
let server;
let closing = false;
async function close() {
  if (closing) return;
  closing = true;
  if (server && server.exitCode === null) {
    const exited = new Promise(resolve => server.once('exit', resolve));
    server.kill();
    await exited;
  }
  if (!/^editor_test_\d+$/.test(schema)) throw new Error('Invalid test schema');
  await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
  await pool.end();
}
process.on('SIGINT', () => close());
process.on('SIGTERM', () => close());
(async () => {
  if (cleanup) { await close(); console.log(`Removed ${schema}`); return; }
  await pool.query(`CREATE SCHEMA "${schema}"`);
  for (const table of ['Profile','Project','Experience','Leadership','Achievement','Tagline','Resume','SiteMedia']) {
    await pool.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING ALL)`);
    await pool.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN "id" DROP DEFAULT`);
    await pool.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY`);
    await pool.query(`INSERT INTO "${schema}"."${table}" SELECT * FROM public."${table}"`);
    const { rows } = await pool.query(`SELECT COALESCE(MAX("id"),0)+1 AS next FROM "${schema}"."${table}"`);
    await pool.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN "id" RESTART WITH ${Number(rows[0].next)}`);
  }
  await pool.query(`ALTER TABLE "${schema}"."SiteMedia" ALTER COLUMN "id" RESTART WITH 1`);
  await pool.query(`ALTER TABLE "${schema}"."Profile" ADD CONSTRAINT editor_test_failure CHECK ("headline" <> '__editor_storage_failure__')`);
  const url = new URL(process.env.DATABASE_URL);
  url.searchParams.set('options', `-c search_path=${schema}`);
  fs.mkdirSync('.local/editor-verification', { recursive: true });
  const log = fs.openSync('.local/editor-verification/server.log','w');
  server = spawn(process.execPath, ['--enable-source-maps','artifacts/api-server/dist/index.mjs'], {
    windowsHide: true,
    env: { ...process.env, DATABASE_URL: url.toString(), APP_COMMIT_SHA:'editor-isolated-verification', RENDER_GIT_COMMIT:'', PORT:'3100', NODE_ENV:'production', STATIC_ROOT:path.resolve('artifacts/mark-andrei-portfolio/dist/public'), VIEW_COUNTER_IGNORED_IPS:'127.0.0.1,::1' },
    stdio: ['ignore',log,log],
  });
  server.on('exit', () => { if (!closing) void close(); });
  console.log(`Isolated editor test server: http://localhost:3100 (${schema}). Ctrl+C removes test schema.`);
  if (process.argv.includes('--verify')) {
    for (let attempt=0; attempt<30; attempt++) {
      try { if ((await fetch('http://localhost:3100/health')).ok) break; } catch {}
      await new Promise(resolve=>setTimeout(resolve,500));
    }
    const test = spawn(process.execPath, ['scripts/verify-editor.cjs'], { windowsHide:true, stdio:'inherit' });
    const code = await new Promise(resolve=>test.once('exit',resolve));
    if (!code && fs.existsSync('.local/verify-local.cjs')) {
      const legacy = spawn(process.execPath, ['.local/verify-local.cjs'], {windowsHide:true,stdio:'inherit',env:{...process.env,PORTFOLIO_CHECK_URL:'http://localhost:3100'}});
      const legacyCode = await new Promise(resolve=>legacy.once('exit',resolve));
      if(legacyCode)process.exitCode=legacyCode;
    }
    await close();
    process.exitCode=code || process.exitCode || 0;
  }
})().catch(async error => { console.error(error.message); await close(); process.exitCode=1; });
